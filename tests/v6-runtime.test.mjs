test('empty design, physical capacities, task priority gate and unlocked revisits', () => {
  const s = new appState.constructor();
  assert.deepEqual(s.selectedTasks, ['TASK_1','TASK_4','TASK_5','TASK_6']);
  assert.equal(s.installedSensors.size, 0);
  assert.equal(s.installedActuators.size, 0);
  assert.ok(s.rules.every(r => Object.values(r.slots).every(v => v === null)));
  assert.equal(s.setStep(4), false);
  assert.equal(s.setStep(2), false);
  s.setTaskPriority('TASK_1','thorough');
  assert.equal(s.setStep(2), true);
  assert.equal(s.canContinue(2), true);
  for(let i=1;i<=11;i++) s.toggleSensor(`SENSE_${String(i).padStart(2,'0')}`);
  assert.equal(s.toggleSensor('SENSE_12').success, false);
  assert.equal(s.setStep(3), true);
  for(let i=0;i<10;i++) s.toggleActuator(`module${i}`);
  assert.equal(s.toggleActuator('extra').success, false);
  assert.equal(s.setStep(4), true);
  assert.equal(s.setRuleSlot(0,'action','SENSE_01'), false);
  s.setRuleSlot(0,'sense','SENSE_01');
  s.setRuleSlot(0,'action','ACT_09');
  assert.equal(s.canContinue(), true);
  assert.equal(s.setStep(5), true);
  assert.equal(s.setStep(2), true);
  for(const id of [...s.installedSensors]) s.toggleSensor(id);
  assert.equal(s.setStep(5), true);
  assert.deepEqual(s.revisitedSteps, [2]);
});

test('CSV contains exactly five fields and escapes quoted multiline notes', () => {
  const s = new appState.constructor(), log = new SessionLogger(s);
  s.addObservationStamp('?', '"spill",\nnear cat');
  const row = log.events[0];
  assert.deepEqual(Object.keys(row), ['timestamp','step','event','target_id','detail']);
  assert.equal(row.event, 'STAMP');
  assert.equal(log.exportCSV().split('\r\n')[0], 'timestamp,step,event,target_id,detail');
  assert.ok(log.exportCSV().includes('""'));
  assert.ok(!log.exportCSV().includes('ParticipantID'));
});

test('empty rules stay idle, private diagnostics are isolated, preview is excluded from run history', () => {
  appState.rules.forEach(r => Object.keys(r.slots).forEach(k => r.slots[k] = null));
  const engine = new SimulationEngine(new ApartmentWorld());
  assert.equal(engine.evaluateRules({}), null);
  const before = { x:engine.world.robot.x, y:engine.world.robot.y };
  engine.tick();
  assert.equal(engine.world.robot.x, before.x);
  assert.equal(engine.world.robot.y, before.y);
  appState.weights = { Coverage:0, Safety:50, Time:0, Hazard:0 };
  engine.computeScores();
  assert.equal(engine.scores.composite, 50);
  const count = appState.runHistory.length;
  engine.startPreview(); engine.stopPreview();
  assert.equal(engine.endRun(), null);
  assert.equal(appState.runHistory.length, count);
  let prompts=0;
  const off = appState.on('reflectionNeeded', () => prompts++);
  engine.start(); engine.stop();
  engine.runLimitSeconds = 0.1;
  engine.tick(); engine.tick();
  assert.equal(prompts, 0);
  const snapshot = engine.endRun();
  assert.equal(prompts, 1);
  assert.equal(appState.runHistory.length, count+1);
  assert.equal(snapshot.passed,false);
  assert.equal('scores' in snapshot,false);
  assert.deepEqual(snapshot.tasksCompleted, []);
  assert.equal(engine.endRun(), null);
  off();
});

test('mounted secondary sensor channels report modeled sources without invented physical measurements', () => {
  const world = new ApartmentWorld(), engine = new SimulationEngine(world);
  appState.installedSensors = new Set(['SENSE_10','SENSE_11','SENSE_13','SENSE_14']);
  let readings = engine.readSensors();
  assert.equal(readings.SENSE_10, 'NOT_MODELLED');
  assert.equal(readings.SENSE_11, 0);
  assert.equal(readings.SENSE_13, 'QUIET');
  assert.equal(readings.SENSE_14, 'CLEAR');
  world.ambientLux = 210;
  world.robot.heldObject = { weightGrams: 125 };
  world.robot.vacuumActive = true;
  readings = engine.readSensors();
  assert.equal(readings.SENSE_10, 210);
  assert.equal(readings.SENSE_11, 125);
  assert.equal(readings.SENSE_13, 'LOUD');
  appState.installedSensors.clear();
  readings = engine.readSensors();
  for(const id of ['SENSE_10','SENSE_11','SENSE_13','SENSE_14']) assert.equal(readings[id], 'NOT_INSTALLED');
});

test('preview restores entity identities, world values, counters and speed stays in preview mode', () => {
  appState.sessionFinished = false;
  const world = new ApartmentWorld(), engine = new SimulationEngine(world);
  const robot = world.robot, dirt = world.dirtCells, cell = dirt[0], objects = world.objects;
  const before = JSON.stringify(world);
  engine.startPreview();
  engine.tick();
  world.dirtCells[0].cleaned = true;
  world.robot.heldObject = world.objects[0];
  engine.catSafetyViolations = 7;
  engine.setSpeed(2);
  assert.equal(engine.previewActive, true);
  assert.equal(engine.runActive, false);
  engine.stopPreview();
  assert.equal(world.robot, robot);
  assert.equal(world.dirtCells, dirt);
  assert.equal(world.dirtCells[0], cell);
  assert.equal(world.objects, objects);
  assert.equal(JSON.stringify(world), before);
  assert.equal(engine.catSafetyViolations, 0);
  assert.equal(engine.tickCount, 0);
  engine.start(); engine.stop();
  assert.equal(engine.runBaseline.time, 100);
  engine.endRun();
});

test('run end logs step five, replaces stale reflection once, and finished sessions cannot start', () => {
  appState.sessionFinished = false;
  const engine = new SimulationEngine(new ApartmentWorld()), logger = new SessionLogger(appState);
  let cleared = 0;
  const off = appState.on('reflectionSelected', e => { if(e.cleared) cleared++; });
  engine.start(); engine.stop();
  cleared = 0;
  appState.reflectionPrompt = { shownAt: Date.now() };
  appState.currentStep = 2;
  engine.endRun('revision');
  assert.equal(appState.reflectionPrompt.runId,1);
  const ended=logger.events.findLast(e=>e.event==='RUN_ENDED');
  assert.equal(ended.step, 5);
  assert.equal(cleared, 1);
  appState.reflectionPrompt = {};
  engine.reset();
  assert.equal(appState.reflectionPrompt, null);
  appState.sessionFinished = true;
  engine.start(); engine.startPreview();
  assert.equal(engine.tickInterval, null);
  assert.equal(engine.runActive, false);
  appState.sessionFinished = false;
  off();
});
